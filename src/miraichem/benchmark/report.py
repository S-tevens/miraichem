"""Generate docs/RESULTS.md from saved results.

Every number in the report is read from result files that were produced by real runs; nothing is
typed in by hand. Simulator results and real-hardware results are labelled separately.
"""

from __future__ import annotations

import statistics
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path

from miraichem.backends.hardware import DEFAULT_HARDWARE_DIR
from miraichem.backends.hardware_eval import HardwareResult
from miraichem.benchmark.ranking import Weights, describe, recommend
from miraichem.benchmark.ranking_scan import recommend_across_scan
from miraichem.vqe.result import RunResult

MITIGATIONS = ["none", "readout", "zne", "readout+zne"]
BACKEND_TITLES = {
    "ideal": "ideal statevector simulator",
    "noisy": "noisy simulator (fake IBM backend)",
}


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    """A GitHub-flavoured markdown table."""
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _fmt(x: float | None, digits: int = 3) -> str:
    return "-" if x is None else f"{x:.{digits}g}"


def load_hardware_results(hardware_dir: Path = DEFAULT_HARDWARE_DIR) -> list[HardwareResult]:
    """Every saved hardware comparison (``results/hardware/<molecule>/<hash>_hw.json``)."""
    return [
        HardwareResult.model_validate_json(p.read_text())
        for p in sorted(Path(hardware_dir).glob("*/*_hw.json"))
    ]


def _overview(results: list[RunResult]) -> str:
    ok = [r for r in results if r.status == "ok"]
    versions = next((r.library_versions for r in reversed(ok) if r.library_versions), {})
    commits = sorted({r.git_commit for r in ok if r.git_commit})
    by: dict[tuple[str, str], int] = defaultdict(int)
    for r in ok:
        by[(r.config.molecule.name, r.config.backend)] += 1
    rows = [[m, b, str(n)] for (m, b), n in sorted(by.items())]
    lines = [
        f"This report was generated by `miraichem report` on "
        f"{datetime.now(UTC).strftime('%Y-%m-%d')} from **{len(results)}** saved runs "
        f"({len(ok)} succeeded, {len(results) - len(ok)} failed).",
        "",
        "- Energies are **total energies in Hartree**; errors are measured against the exact "
        "energy (FCI for the full space, CASCI inside an active space) and shown in "
        "milli-Hartree (mHa). *Chemical accuracy* means an error below 1.6 mHa.",
        "- Simulator results (ideal and noisy) are kept separate from real-hardware results.",
        "",
        md_table(["Molecule", "Backend", "Successful runs"], rows),
    ]
    if versions:
        lines += [
            "",
            "Library versions: " + ", ".join(f"{k} {v}" for k, v in versions.items()) + ".",
        ]
    if commits:
        lines += [f"Runs were produced at git commit(s): {', '.join(commits)}."]
    return "\n".join(lines)


def _top_table(rec, top: int) -> str:
    rows = []
    for x in rec.ranked[:top]:
        marks = ("S" if x.on_front_shots else "") + ("G" if x.on_front_gates else "")
        gates = _fmt(x.result.two_qubit_gates, 4) if x.result.two_qubit_gates is not None else "-"
        rows.append(
            [
                str(x.rank),
                x.label,
                _fmt(x.error_mha),
                "yes" if x.within_chemical_accuracy else "no",
                gates,
                f"{x.shots:,}",
                f"{x.score:.3f}",
                marks,
            ]
        )
    return md_table(
        ["#", "Configuration", "Error (mHa)", "Chem. acc.", "2q gates", "Shots", "Score", "Pareto"],
        rows,
    )


def _mitigation_table(runs: list[RunResult]) -> str | None:
    """Best (and median) error per mapping/ansatz for each mitigation mode, noisy runs only."""
    groups: dict[tuple[str, str], dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    for r in runs:
        if r.abs_error_mha is not None:
            groups[(r.config.mapping, f"{r.config.ansatz}")][r.config.mitigation].append(
                r.abs_error_mha
            )
    if not any(len(m) > 1 for m in groups.values()):
        return None  # nothing to compare
    rows = []
    for (mapping, ansatz), by_mit in sorted(groups.items()):
        cells = []
        for mit in MITIGATIONS:
            v = by_mit.get(mit)
            cells.append("-" if not v else f"{min(v):.3g} ({statistics.median(v):.3g}; n={len(v)})")
        rows.append([mapping, ansatz, *cells])
    return md_table(["Mapping", "Ansatz", *MITIGATIONS], rows)


def _backend_section(results: list[RunResult], molecule: str, backend: str, top: int) -> str | None:
    runs = [
        r
        for r in results
        if r.status == "ok"
        and r.config.molecule.name.lower() == molecule.lower()
        and r.config.backend == backend
    ]
    if not runs:
        return None
    parts = [f"### {molecule}: {BACKEND_TITLES.get(backend, backend)}", ""]
    scan_part: list[str] = []
    geometry_part: list[str] = []
    try:
        scan = recommend_across_scan(results, molecule, backend)
        rows = [
            [
                str(s.rank),
                s.label,
                str(len(s.bond_lengths)),
                _fmt(s.worst_error_mha),
                _fmt(s.mean_error_mha),
                f"{s.coverage:.0%}",
            ]
            for s in scan.ranked
        ]
        scan_part = [
            f"**Recommendation across a bond-length scan** ({scan.n_configs} configurations; "
            "the more reliable of the two recommendations, because a configuration that is "
            "accurate near equilibrium can fail when the bond is stretched):",
            "",
            scan.justification,
            "",
            md_table(
                ["#", "Configuration", "Points", "Worst (mHa)", "Mean (mHa)", "Coverage"], rows
            ),
            "",
        ]
    except ValueError:
        pass
    bond = None
    try:
        rec = recommend(results, molecule, backend, Weights())
        bond = rec.best.result.config.bond_length
        geometry_part = [
            f"**Recommendation at one geometry** ({len(rec.ranked)} runs, bond length {bond} A):",
            "",
            rec.justification,
            "",
            _top_table(rec, top),
            "",
            "Pareto marks: S = on the error-vs-shots front, G = on the error-vs-two-qubit-gates "
            "front.",
        ]
    except ValueError:
        pass
    parts += scan_part + geometry_part
    if backend != "ideal":
        at_bond = [r for r in runs if bond is None or r.config.bond_length == bond]
        table = _mitigation_table(at_bond)
        if table:
            parts += [
                "",
                f"**Effect of error mitigation** at bond length {bond} A (best error in mHa, with "
                "the median and number of runs in brackets; one seed per configuration, so small "
                "differences are not statistically meaningful):",
                "",
                table,
            ]
    return "\n".join(parts)


def _hardware_section(hardware: list[HardwareResult]) -> str:
    if not hardware:
        return (
            "No real-hardware results have been saved. Run `miraichem hardware ...` "
            "(see the README) to add them."
        )
    parts = [
        "These numbers come from **real IBM quantum hardware**. Each row re-evaluates the optimal "
        "parameters of a saved simulator run on the device (fixed-parameter evaluation, no "
        "optimisation on hardware)."
    ]
    for h in hardware:
        parts += [
            "",
            f"**{h.molecule}** at {h.bond_length} A on `{h.backend}`, {h.shots} shots per circuit "
            f"(source simulator run `{h.source_config_hash}`).",
            "",
        ]
        rows = [
            ["Exact", f"{h.e_exact:.6f}", "0", "reference"],
            ["Ideal circuit at these parameters", f"{h.e_ideal_at_params:.6f}",
             _fmt(abs(h.e_ideal_at_params - h.e_exact) * 1000), "noiseless simulation"],
            [f"Noisy simulator ({h.simulator_mitigation})", f"{h.e_simulator:.6f}",
             _fmt(abs(h.e_simulator - h.e_exact) * 1000), "simulator"],
        ]  # fmt: skip
        rows += [
            [
                f"Hardware ({e.mitigation})",
                f"{e.e_hw:.6f}",
                _fmt(e.abs_error_mha),
                f"real device, job `{e.job_id}`",
            ]
            for e in h.evaluations
        ]
        parts.append(md_table(["Source", "Energy (Ha)", "Error (mHa)", "Kind"], rows))
    return "\n".join(parts)


def _figures_section(molecules: list[str], figures_dir: Path) -> str | None:
    lines = []
    for mol in molecules:
        for png in sorted(Path(figures_dir).glob(f"dissociation_{mol.lower()}_*.png")):
            lines.append(f"![{png.stem}]({png.relative_to(figures_dir.parent).as_posix()})")
    return "\n\n".join(lines) if lines else None


CAVEATS = """\
- **Small molecules.** H2 (4 qubits, 2 with Parity) and LiH (a 2-electron, 3-orbital active space) in
  the STO-3G basis. These are benchmarks of the *method*, not chemistry that a classical computer cannot do.
- **One seed per configuration.** Results with shot noise (noisy simulator, SPSA) vary from run to run;
  differences of a few mHa between configurations are not statistically resolved.
- **Mixed sweep settings.** Runs from different sweeps (different `maxiter` and shot budgets) are ranked
  together, so rankings partly reflect those budgets.
- **Simulator is not hardware.** The noisy simulator uses a snapshot of a fake IBM device's noise model;
  real devices drift and have errors that are not modelled (crosstalk, leakage).
- **Hardware budget.** Real-hardware time on the free plan is limited, so only a few configurations were
  evaluated on a real device, at fixed parameters.
- **Energies of LiH** are compared with CASCI in the same active space, not with full FCI."""  # noqa: E501


def generate_report(
    results: list[RunResult],
    hardware: list[HardwareResult] | None = None,
    figures_dir: Path | None = Path("docs/figures"),
    top: int = 5,
) -> str:
    """Build the RESULTS.md text from saved results."""
    hardware = hardware or []
    parts = ["# Results", ""]
    if not results:
        return (
            "# Results\n\nNo saved results were found. Run `miraichem sweep configs/sweeps/"
            "quick_h2.yaml` first.\n"
        )
    parts += [_overview(results), "", "## Simulator results", ""]
    molecules = sorted({r.config.molecule.name for r in results if r.status == "ok"})
    for mol in molecules:
        for backend in ("ideal", "noisy"):
            section = _backend_section(results, mol, backend, top)
            if section:
                parts += [section, ""]
    parts += ["## Real hardware results", "", _hardware_section(hardware), ""]
    figures = _figures_section(molecules, figures_dir) if figures_dir else None
    if figures:
        parts += ["## Dissociation curves", "", figures, ""]
    parts += ["## Limitations and honest notes", "", CAVEATS, ""]
    return "\n".join(parts)


def write_report(
    results: list[RunResult],
    output: Path,
    hardware: list[HardwareResult] | None = None,
    figures_dir: Path | None = Path("docs/figures"),
) -> Path:
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generate_report(results, hardware, figures_dir), encoding="utf-8")
    return output


__all__ = ["describe", "generate_report", "load_hardware_results", "md_table", "write_report"]
